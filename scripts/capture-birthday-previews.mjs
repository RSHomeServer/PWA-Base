/**
 * Capture Constellation Image A (full first frame) + Image B (stage crop)
 * and write bbox metadata for the Home → experience zoom transition.
 *
 * Usage:
 *   BIRTHDAY_PREVIEW_BASE=http://127.0.0.1:4194 node scripts/capture-birthday-previews.mjs
 */
import { mkdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { chromium } from "@playwright/test";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, "..");
const outDir = path.join(
  root,
  "apps/birthday-web/public/previews/constellation",
);
const metaPath = path.join(
  root,
  "packages/site-birthday/src/experiences/previews/constellation/meta.json",
);

const base = process.env.BIRTHDAY_PREVIEW_BASE ?? "http://127.0.0.1:4194";
const viewport = { width: 1280, height: 800 };

await mkdir(outDir, { recursive: true });

const browser = await chromium.launch({ headless: true });
const page = await browser.newPage({
  viewport,
  deviceScaleFactor: 1,
});

await page.goto(`${base}/constellation`, { waitUntil: "networkidle" });
await page.waitForSelector("[data-constellation-stage]");
// First paint with constellation visible; capture before opening text dominates.
await page.waitForTimeout(400);

const stage = page.locator("[data-constellation-stage]");
const stageBox = await stage.boundingBox();
if (!stageBox) {
  throw new Error("Constellation stage bounding box missing");
}

const fullPath = path.join(outDir, "frame-full.png");
const cropPath = path.join(outDir, "frame-crop.png");

await page.screenshot({ path: fullPath, type: "png" });
await stage.screenshot({ path: cropPath, type: "png" });

const bbox = {
  x: stageBox.x / viewport.width,
  y: stageBox.y / viewport.height,
  width: stageBox.width / viewport.width,
  height: stageBox.height / viewport.height,
};
const center = {
  x: (stageBox.x + stageBox.width / 2) / viewport.width,
  y: (stageBox.y + stageBox.height / 2) / viewport.height,
};

const meta = {
  bbox,
  center,
  widthPx: Math.round(stageBox.width),
  heightPx: Math.round(stageBox.height),
  viewport,
  notes: "Generated by scripts/capture-birthday-previews.mjs",
  capturedAt: new Date().toISOString(),
};

await writeFile(metaPath, `${JSON.stringify(meta, null, 2)}\n`, "utf8");

// Before/after transition frames for validation gallery
const artifactsDir = path.join(root, "docs/artifacts/birthday-transition");
await mkdir(artifactsDir, { recursive: true });
await page.screenshot({
  path: path.join(artifactsDir, "constellation-first-frame.png"),
  type: "png",
});

await page.goto(`${base}/`, { waitUntil: "networkidle" });
await page.getByRole("button", { name: "Load Experiences" }).click();
await page.waitForFunction(() => {
  const items = [...document.querySelectorAll("[data-state]")];
  return (
    items.length >= 1 &&
    items.some(
      (el) =>
        el.textContent?.includes("Constellation") &&
        el.getAttribute("data-state") === "ready",
    )
  );
});
await page.screenshot({
  path: path.join(artifactsDir, "home-before-enter.png"),
  type: "png",
});

await page.getByRole("button", { name: "Enter Constellation" }).click();
await page.waitForTimeout(380);
await page.screenshot({
  path: path.join(artifactsDir, "transition-mid.png"),
  type: "png",
});
await page.waitForURL(/\/constellation$/);
await page.waitForTimeout(200);
await page.screenshot({
  path: path.join(artifactsDir, "constellation-after-enter.png"),
  type: "png",
});

await browser.close();

console.log("Wrote", fullPath);
console.log("Wrote", cropPath);
console.log("Wrote", metaPath);
console.log(
  "bbox",
  JSON.stringify(bbox),
  "center",
  JSON.stringify(center),
);
